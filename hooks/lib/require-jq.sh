#!/usr/bin/env bash
# require-jq.sh — общий fail-closed гейт на доступность JSON-парсера.
#
# Подключается первой строкой хука:  source "${BASH_SOURCE[0]%/*}/lib/require-jq.sh"
# (именно раскрытием bash, а не через $(dirname …): в урезанном окружении внешнего
# dirname может не быть, и тогда гейт молча не подгрузился бы — ровно тот отказ,
# который он призван закрыть.)
# (в common.sh уже подключён — хукам, которые его используют, отдельная строка
# не нужна).
#
# ЗАЧЕМ. Разбор события хука держится на jq. Раньше при его отсутствии хук падал
# на первом же вызове с exit 127, а рантайм трактует как блокировку ТОЛЬКО
# exit 2 — любой другой код означает «хук не сработал, продолжаем». В результате
# 11 из 16 хуков молча переставали применять политику, при этом settings.json
# продолжал показывать их включёнными, а `harness.sh doctor` не проверял jq
# вовсе. Подтверждено e2e-прогоном: на машине без jq коммит с сообщением
# "fixed stuff" спокойно проходил commit-message-format.sh.
#
# Для compliance-слоя это худший из режимов отказа: защита выглядит включённой,
# но не применяется. Поэтому невозможность применить политику = отказ, а не
# пропуск (fail-closed).
#
# Что даёт exit 2 на разных событиях — ровно нужное разделение, без ветвления:
#   PreToolUse / Stop        — вызов блокируется (политику применить нельзя);
#   события без блокировки   — инструмент уже отработал, агент просто получает
#                              причину в stderr, то есть громкое предупреждение.
#
# Решение печатается в stdout — единственный поток, который рантаймы разбирают
# как JSON. hookSpecificOutput здесь не проставляется: чтобы узнать имя события,
# нужен jq, а его как раз и нет. Для GigaCode блокировку в этом случае несёт
# exit 2 + stderr, для Qwen/GigaCode — пара decision/reason.
#
# НЕ подключается в sdd-schema-gate.sh: там есть рабочий grep-fallback, хук без
# jq деградирует корректно, а не отказывает.

if ! command -v jq >/dev/null 2>&1; then
  # Причина зашита статически: экранировать её через jq здесь, очевидно, нечем.
  # Пути к harness.sh намеренно НЕ зашиты: в GigaCode это
  # .gigacode/scripts/harness.sh, в GigaCode-расширении — ${extensionPath}/scripts/.
  # Ссылаемся на команду, она одинакова в обоих (/harness и /pdls:harness).
  _RJQ_REASON="harness: jq не найден в PATH. На нём держится разбор события у 11 из 16 хуков, поэтому enforcement-слой применить нельзя и вызов заблокирован (fail-closed, а не тихий пропуск). Установи jq: brew install jq | apt-get install jq | winget install jqlang.jq. Проверить окружение целиком: команда /harness doctor (в GigaCode — /pdls:harness doctor). Если хук нужно временно снять: /harness hooks disable <name> — это осознанное решение с фиксацией причины, в отличие от молчаливого отказа."
  printf '{"decision":"deny","reason":"%s"}\n' "$_RJQ_REASON"
  printf '%s\n' "$_RJQ_REASON" >&2
  exit 2
fi
